/** Maximum weight each question can contribute to a dimension (for normalisation). */
export function maxWeightsByDimension(): Record<string, number> {
  const totals: Record<string, number> = {};
  for (const question of QUESTIONS) {
    const best: Record<string, number> = {};
    for (const option of question.options) {
      for (const [dimension, weight] of Object.entries(option.weights)) {
        best[dimension] = Math.max(best[dimension] ?? 0, weight ?? 0);
      }
    }
    for (const [dimension, weight] of Object.entries(best)) {
      totals[dimension] = (totals[dimension] ?? 0) + weight;
    }
  }
  return totals;
}
